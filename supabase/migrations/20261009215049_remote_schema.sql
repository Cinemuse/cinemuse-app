CREATE VIEW "public"."user_stats" WITH (security_invoker=on) AS  WITH logs_with_runtime AS (
         SELECT wl.user_id,
            wl.tmdb_id,
            wl.media_type,
            wl.season,
            wl.episode,
            wl.logged_at,
            COALESCE(mc.runtime_minutes,
                CASE
                    WHEN (wl.media_type = 'movie'::public.media_kind) THEN 120
                    ELSE 45
                END) AS runtime
           FROM (public.watch_logs wl
             LEFT JOIN public.media_cache mc ON (((mc.tmdb_id = wl.tmdb_id) AND (mc.media_type = wl.media_type))))
        )
 SELECT user_id,
    COALESCE(sum(runtime), (0)::bigint) AS total_minutes_watched,
    count(
        CASE
            WHEN (media_type = 'tv'::public.media_kind) THEN 1
            ELSE NULL::integer
        END) AS total_episodes,
    count(DISTINCT
        CASE
            WHEN (media_type = 'movie'::public.media_kind) THEN tmdb_id
            ELSE NULL::bigint
        END) AS total_movies,
    count(DISTINCT
        CASE
            WHEN (media_type = 'tv'::public.media_kind) THEN tmdb_id
            ELSE NULL::bigint
        END) AS total_series,
    count(DISTINCT
        CASE
            WHEN (media_type = 'tv'::public.media_kind) THEN (((tmdb_id)::text || '-'::text) || (season)::text)
            ELSE NULL::text
        END) AS total_seasons,
    COALESCE(sum(
        CASE
            WHEN (media_type = 'movie'::public.media_kind) THEN runtime
            ELSE 0
        END), (0)::bigint) AS movie_minutes,
    COALESCE(sum(
        CASE
            WHEN (media_type = 'tv'::public.media_kind) THEN runtime
            ELSE 0
        END), (0)::bigint) AS series_minutes,
    COALESCE(sum(
        CASE
            WHEN (logged_at >= (now() - '7 days'::interval)) THEN runtime
            ELSE 0
        END), (0)::bigint) AS p7_minutes,
    count(
        CASE
            WHEN ((logged_at >= (now() - '7 days'::interval)) AND (media_type = 'movie'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p7_movies,
    count(
        CASE
            WHEN ((logged_at >= (now() - '7 days'::interval)) AND (media_type = 'tv'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p7_episodes,
    COALESCE(sum(
        CASE
            WHEN (logged_at >= (now() - '30 days'::interval)) THEN runtime
            ELSE 0
        END), (0)::bigint) AS p30_minutes,
    count(
        CASE
            WHEN ((logged_at >= (now() - '30 days'::interval)) AND (media_type = 'movie'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p30_movies,
    count(
        CASE
            WHEN ((logged_at >= (now() - '30 days'::interval)) AND (media_type = 'tv'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p30_episodes,
    COALESCE(sum(
        CASE
            WHEN (logged_at >= (now() - '365 days'::interval)) THEN runtime
            ELSE 0
        END), (0)::bigint) AS p365_minutes,
    count(
        CASE
            WHEN ((logged_at >= (now() - '365 days'::interval)) AND (media_type = 'movie'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p365_movies,
    count(
        CASE
            WHEN ((logged_at >= (now() - '365 days'::interval)) AND (media_type = 'tv'::public.media_kind)) THEN 1
            ELSE NULL::integer
        END) AS p365_episodes
   FROM logs_with_runtime
  GROUP BY user_id;

