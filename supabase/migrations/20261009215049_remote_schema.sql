CREATE OR REPLACE FUNCTION public.update_watch_history_from_logs()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
begin
  if (TG_OP = 'INSERT') then
    insert into public.watch_history (
      user_id, tmdb_id, media_type, season, episode, status, watch_count, last_watched_at
    )
    values (
      NEW.user_id, NEW.tmdb_id, NEW.media_type, NEW.season, NEW.episode, 'completed', 1, NEW.logged_at
    )
    -- Using the explicit constraint name avoids all ambiguity
    on conflict on constraint watch_history_pkey 
    do update set 
      status = 'completed',
      watch_count = watch_history.watch_count + 1,
      last_watched_at = NEW.logged_at,
      progress_seconds = 0;
  end if;

  if (TG_OP = 'DELETE') then
    update public.watch_history
    set watch_count = greatest(0, watch_count - 1)
    where user_id = OLD.user_id 
      and tmdb_id = OLD.tmdb_id 
      and media_type = OLD.media_type
      and season = OLD.season
      and episode = OLD.episode;
  end if;

  return null;
end;
$function$;

