CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$
begin
  insert into public.profiles (id, username, avatar_url)
  values (new.id, new.raw_user_meta_data->>'username', new.raw_user_meta_data->>'avatar_url');

  insert into public.lists (user_id, type, name)
  values 
    (new.id, 'watchlist', 'Watchlist'),
    (new.id, 'favorites', 'Favorites');
    
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.protect_system_lists()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.type IN ('watchlist', 'favorites') THEN
      RAISE EXCEPTION 'Cannot delete system lists';
    END IF;
    RETURN OLD;
  ELSIF TG_OP = 'UPDATE' THEN
    IF OLD.type IN ('watchlist', 'favorites') AND NEW.type != OLD.type THEN
      RAISE EXCEPTION 'Cannot change the type of a system list';
    END IF;
    RETURN NEW;
  END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.sync_history_from_log()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
    BEGIN
      IF (TG_OP = 'INSERT') THEN
        INSERT INTO public.watch_history (user_id, tmdb_id, media_type, season, episode, status, watch_count, last_watched_at)
        VALUES (NEW.user_id, NEW.tmdb_id, NEW.media_type, NEW.season, NEW.episode, 'completed', 1, NEW.logged_at)
        ON CONFLICT ON CONSTRAINT watch_history_pkey 
        DO UPDATE SET 
          status = 'completed',
          watch_count = watch_history.watch_count + 1,
          last_watched_at = NEW.logged_at,
          progress_seconds = 0;
      END IF;

      IF (TG_OP = 'DELETE') THEN
        UPDATE public.watch_history
        SET watch_count = greatest(0, watch_count - 1)
        WHERE user_id = OLD.user_id AND tmdb_id = OLD.tmdb_id 
          AND media_type = OLD.media_type AND season = OLD.season AND episode = OLD.episode;
      END IF;

      RETURN NULL;
    END;
    $function$;

